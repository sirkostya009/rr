// routePatterns lists the patterns of a route set, as written.
func routePatterns(routes []route) []string {
	pats := make([]string, len(routes))
	for i, rt := range routes {
		pats[i] = rt.pattern
	}
	return pats
}

func isDynamic(rt route) bool {
	for _, t := range rt.tokens {
		if t.kind != tokLit {
			return true
		}
	}
	return false
}

var (
	// -helpers: import path of a package holding pools shared by every
	// generated dispatcher in the tree, so N packages don't mean N pools
	helpersPkg string

	// -nopathvalue: emit no SetPathValue calls, sparing the per-request map
	noPathValue bool
)

// resolvePool looks for an exported *sync.Pool-ish var named `name` in the
// -helpers package and returns the expression generated code should use, plus
// the import it needs. ok=false means fall back to a package-local pool: the
// flag is absent, the package doesn't have that var, and either is fine.
func resolvePool(name, outDir string) (expr, imp string, ok bool) {
	if helpersPkg == "" {
		return "", "", false
	}
	s := scan(helpersPkg)
	t, found := s.Vars[name]
	if !found {
		return "", "", false
	}
	if t != "sync.Pool" && t != "*sync.Pool" && !strings.HasPrefix(t, "sync.Pool{") {
		fatalf("-helpers %s: %s is %s, want sync.Pool or *sync.Pool", helpersPkg, name, t)
	}
	if s.Dir == outDir { // helpers live in the package being generated
		return name, "", true
	}
	return s.Name + "." + name, helpersPkg, true
}

// scan reads a package the generator only needs to look at, never to load.
func scan(pkgPath string) *gen.PkgInfo {
	info, err := gen.Scan(pkgPath)
	if err != nil {
		fatalf("%v", err)
	}
	return info
}

// foreignGgen reports whether pkgPath's typeName has the ggen method: either
// already generated, or promised by a //ggen:generate directive, so the
// sibling's ggen run need not come first.
func foreignGgen(pkgPath, typeName, method string) bool {
	s := scan(pkgPath)
	if s.Std {
		return false
	}
	if _, ok := s.GgenTypes[typeName]; ok {
		return true
	}
	_, ok := s.Methods[typeName][method]
	return ok
}
