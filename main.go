// Command rr generates ServeHTTP routing code from //rr: directives.
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/printer"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"github.com/sirkostya009/rr/gen"
)

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "rr: "+format+"\n", args...)
	os.Exit(1)
}

func main() {
	var inputs []string
	var out string
	args := os.Args[1:]
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "-o":
			i++
			if i == len(args) {
				fatalf("-o requires a value")
			}
			out = args[i]
		case "-helpers":
			i++
			if i == len(args) {
				fatalf("-helpers requires an import path")
			}
			helpersPkg = args[i]
		case "-nopathvalue":
			noPathValue = true
		case "-hashmin":
			i++
			if i == len(args) {
				fatalf("-hashmin requires a value")
			}
			n, err := strconv.Atoi(args[i])
			if err != nil || n < -1 {
				fatalf("-hashmin: want an integer >= -1 (0 = always, -1 = never), got %q", args[i])
			}
			hashMin = n
		case "-h", "--help":
			fmt.Println("usage: rr [-o output.go] [-helpers import/path] [-nopathvalue] [-hashmin n] input.go...")
			return
		default:
			inputs = append(inputs, args[i])
		}
	}
	if len(inputs) == 0 {
		fatalf("no input files")
	}
	if out == "" {
		out = strings.TrimSuffix(inputs[0], ".go") + "_gen.go"
	} else if !strings.HasSuffix(out, ".go") {
		out += ".go"
	}
	outAbs, err := filepath.Abs(out)
	if err != nil {
		fatalf("%v", err)
	}
	for _, in := range inputs {
		if _, err := os.Stat(in); err != nil { //nolint:gosec // a CLI path argument is meant to point anywhere
			fatalf("%v", err)
		}
	}

	// the input file only anchors the package directory and names the output;
	// directives are read from every file in the package
	set, err := gen.Load(filepath.Dir(inputs[0]))
	if err != nil {
		fatalf("%v", err)
	}
	pkg := set.Packages[0]

	b := &builder{
		fset:         pkg.Fset,
		idx:          pkg.Index(),
		extraImports: map[string]bool{},
		importAlias:  map[string]string{},
		numHelpers:   map[string]bool{},
	}
	b.detectGgen(pkg)
	apis := b.build(pkg)

	g := &emitter{quals: map[string]struct{}{}}
	for _, a := range apis {
		// a central emits below, and an api mounted into one serves through it
		if a.central || a.mounted {
			continue
		}
		g.emitDispatcher(a, a.routes, map[*apiType]string{a: a.recv})
	}
	for _, a := range apis {
		if !a.central {
			continue
		}
		merged := append([]route{}, a.routes...)
		recvOf := map[*apiType]string{a: a.recv}
		for _, m := range a.mounts {
			recvOf[m.api] = a.recv + "." + m.field
			merged = append(merged, m.api.routes...)
		}
		g.emitDispatcher(a, merged, recvOf)
	}

	var buf strings.Builder
	buf.WriteString("// Code generated by rr. DO NOT EDIT.\n\n")
	buf.WriteString("package ")
	buf.WriteString(pkg.Name)
	buf.WriteString("\n\n")
	for q := range g.quals {
		b.noteImportPath(q)
	}
	imports := map[string]bool{"net/http": true}
	if g.useURL {
		imports["net/url"] = true
	}
	if g.useStrings {
		imports["strings"] = true
	}
	for _, a := range apis {
		for _, rt := range a.routes {
			if (rt.retKind == retVal || rt.retKind == retValErr) && rt.enc == ggNone {
				imports["encoding/json"] = true
			}
			for _, spec := range rt.args {
				if spec.kind == argBody && spec.bodyKind == bodyJSON && spec.fast == ggNone {
					imports["encoding/json"] = true
				}
			}
		}
	}
	// resolve the buffer pools before imports are fixed: a shared pool pulls in
	// the helpers package, a local one pulls in sync
	outDir := filepath.Dir(outAbs)
	if g.needsReadPool() {
		if expr, imp, ok := resolvePool("ReaderPool", outDir); ok {
			g.readPool = expr
			if imp != "" {
				imports[imp] = true
			}
		} else {
			g.readPool, g.localRead = "readBufPool", true
		}
	}
	if g.needsWritePool() {
		if expr, imp, ok := resolvePool("WriterPool", outDir); ok {
			g.writePool = expr
			if imp != "" {
				imports[imp] = true
			}
		} else {
			g.writePool, g.localWrite = "writeBufPool", true
		}
	}
	if g.localRead || g.localWrite {
		imports["sync"] = true
	}
	if g.useReadOne || g.useReadSlice || g.useReadSeq || g.useWriteOne || g.useWriteSlice || g.useWriteAny {
		imports[ggenPkg] = true
	}
	if g.useReadSeq {
		imports["iter"] = true
	}
	for p := range b.extraImports {
		imports[p] = true
	}
	sorted := make([]string, 0, len(imports))
	for p := range imports {
		sorted = append(sorted, p)
	}
	slices.Sort(sorted)
	buf.WriteString("import (\n")
	for _, p := range sorted {
		buf.WriteString("\t")
		if alias := b.importAlias[p]; alias != "" {
			buf.WriteString(alias)
			buf.WriteString(" ")
		}
		buf.WriteString(strconv.Quote(p))
		buf.WriteString("\n")
	}
	buf.WriteString(")\n\n")
	if g.useWriteStd || g.useWriteAny || g.useWriteOne || g.useWriteSlice {
		buf.WriteString(helperJSONCT)
	}
	if g.localRead {
		buf.WriteString("var readBufPool = sync.Pool{New: func() any { b := make([]byte, 0, 4096); return &b }}\n\n")
	}
	if g.localWrite {
		buf.WriteString("var writeBufPool = sync.Pool{New: func() any { b := make([]byte, 0, 4096); return &b }}\n\n")
	}
	if g.useReadOne {
		fmt.Fprintf(&buf, helperReadJSON, g.readPool, g.readPool)
	}
	if g.useReadSlice {
		fmt.Fprintf(&buf, helperReadJSONSlice, g.readPool, g.readPool)
	}
	if g.useReadSeq {
		fmt.Fprintf(&buf, helperReadJSONSeq, g.readPool, g.readPool)
	}
	if g.useWriteAny {
		fmt.Fprintf(&buf, helperWriteJSONAny, g.writePool, g.writePool)
	}
	if g.useWriteStd {
		buf.WriteString(helperWriteJSON)
	}
	for _, h := range []string{"parseFloat32"} {
		if b.numHelpers[h] {
			buf.WriteString(numHelperSrc[h])
		}
	}
	buf.WriteString(g.b.String())

	src, err := format.Source([]byte(buf.String()))
	if err != nil {
		_ = os.WriteFile(out, []byte(buf.String()), 0o644) //nolint:gosec // source file
		fatalf("generated code has syntax errors (written unformatted to %s): %v", out, err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil { //nolint:gosec // source file
		fatalf("%v", err)
	}
}

// refExpr is a resolved @ref. Method refs render relative to a receiver
// expression, so the same ref works in a standalone dispatcher ("s.handle")
// and in an app-merged one ("s.Some.handle").
type refExpr struct {
	method bool
	name   string
}

func (r refExpr) isSet() bool { return r.name != "" }

func (r refExpr) expr(recv string) string {
	if r.method {
		return recv + "." + r.name
	}
	return r.name
}

// param type classes; same-class params cannot share a trie position since
// their matchers overlap (any int parses as a float, etc.)
const (
	typString = "string"
	typBool   = "bool"
	typError  = "error"
	pkgHTTP   = "http"
)

const (
	classCustom  = iota // checker/regex/plain: not statically comparable
	classNumeric        // int, float64, float32
	classBool
)

type param struct {
	name      string
	checker   string  // raw @ref from the pattern
	ref       refExpr // resolved checker
	extraArgs string  // appended to the call, e.g. ", 64" for strconv.ParseFloat
	transform bool    // checker returns (T, error); T becomes a handler argument
	ok        bool    // transformer returns (T, bool) instead
	regex     bool    // checker is a *regexp.Regexp var, matched directly
	class     int     // for auto-derived matchers
	typ       string  // transformed value's type when known (derived matchers), for the hoisted slot
}

const (
	tokLit = iota
	tokParam
	tokWild
)

type tok struct {
	kind int
	lit  string // tokLit: one path segment, no slashes
	p    *param // tokParam; tokWild: nil for bare *, else capture name
}

const (
	argParam      = iota // a transformed path param, bound by name
	argBody              // JSON-decoded request body
	argQuery             // query string value(s)
	argHeader            // header value
	argWriter            // http.ResponseWriter, bound by type
	argRequest           // *http.Request, bound by type
	argError             // error, bound by type (error handlers only)
	argWriterCast        // named type embedding http.ResponseWriter, type-asserted from w
	argContext           // context.Context, bound by type, emitted as r.Context()
)

// query binding shapes, decided by the declared param type
const (
	bindScalar = iota // one key, optionally checked/transformed
	bindValues        // url.Values or map[string][]string, passed through
	bindMap           // map[string]string or map[string]any, first values
	bindStruct        // in-package struct, fields bound by `query` tag or name
	bindParser        // @func taking the whole query/header, returning T or (T, error)
)

const (
	fString = iota
	fInt
	fBool
)

// body binding shapes
const (
	bodyJSON      = iota // struct/ggen/map decoded from the JSON body
	bodyMultipart        // multipart.Form (multipart/form-data)
	bodyForm             // url.Values (application/x-www-form-urlencoded)
)

type queryField struct {
	name, key string
	kind      int
}

// argSpec describes one handler parameter, driven by its name, type, and any
// inline /* rr:... */ annotation in the parameter list.
type argSpec struct {
	kind      int
	whole     bool    // query/header: bind the whole object, dispatched by type
	name      string  // path param / query key / header name
	checker   string  // raw @ref for query/header validators and parsers
	ref       refExpr // resolved checker
	transform bool
	ok        bool     // transformer returns (T, bool), not (T, error)
	regex     bool     // checker is a *regexp.Regexp var, matched directly
	typeExpr  ast.Expr // as declared in the handler signature
	typ       string   // rendered type, for body/transformed/struct binds
	ptr       bool     // body declared as *T
	keeps     bool     // *T body the handler may hold on to past the call
	fast      int      // ggen shape of the body type
	bodyKind  int      // argBody: json / multipart / form
	elem      string   // ggSlice, ggSeq: the element type name
	bind      int      // argQuery/argHeader: whole-object binding shape
	mapAny    bool     // bindMap: map[string]any instead of map[string]string
	fields    []queryField
}

// handler return shapes
const (
	retNone = iota
	retErr
	retVal    // T, JSON-encoded
	retValErr // (T, error)
)

// ggen fast-path shapes for a body/response type
const (
	ggNone  = iota // no generated methods, use encoding/json
	ggOne          // T has DecodeFromStream/AppendJSON
	ggSlice        // []T with the methods on T
	ggSeq          // iter.Seq2[T, error] body, T with the methods
	ggAny          // arbitrary value via ggen.AppendAny, when ggen is in play
)

type route struct {
	method  string
	pattern string
	display string // the pattern in ServeMux form, stamped into r.Pattern
	handler string
	errH    ehandler // owner onerror (central covers it at emission)
	retKind int
	retType ast.Expr // first result, for retVal/retValErr
	retTyp  string   // retType rendered, for the hoisted result var (retValErr)
	enc     int      // ggen shape of the response type
	owner   *apiType
	args    []argSpec
	tokens  []tok
}

type mount struct {
	field string
	api   *apiType
}

// xmount is a resolved cross-package delegation: requests under prefix are
// handed to the field's own generated ServeHTTP. prefix is discovered from
// the sub-package's //rr:prefix marker.
type xmount struct {
	field  string
	prefix string
}

// middleware is a guard func: it takes anything a handler can (except path
// params and body) and returns bool (false = handled, stop) or error
// (non-nil goes to the error handler in scope).
type middleware struct {
	ref    refExpr
	retErr bool
	args   []argSpec
}

// ehandler is a resolved 404/405/400/onerror handler. Like a route handler it
// binds params (http.ResponseWriter required; *http.Request, error, query and
// header binds optional), so args carries its signature.
type ehandler struct {
	ref    refExpr
	args   []argSpec
	hasErr bool // declares an error param
}

func (h ehandler) isSet() bool { return h.ref.isSet() }

type apiType struct {
	name    string
	recv    string
	ptr     bool
	central bool // merges routes of api-typed fields into its dispatcher
	mounted bool // merged into some central dispatcher

	middlewares []middleware
	errHandler  ehandler // onerror
	notFound    ehandler // 404
	notAllowed  ehandler // 405
	badReq      ehandler // 400

	mounts  []mount
	xmounts []xmount
	routes  []route
	prefix  string // literal prefix this dispatcher owns
}

// trie over path segments; shared literal prefixes are matched once
type tnode struct {
	routes []route // routes terminating exactly here
	lits   []litEdge
	params []*paramEdge
	wild   *wildEdge
}

type litEdge struct {
	seg   string
	child *tnode
}

type paramEdge struct {
	p     *param
	owner *apiType // for method checkers, whose receiver to call
	child *tnode
}

type wildEdge struct {
	name   string // capture name, "" for bare *
	routes []route
}

func (n *tnode) hasDesc() bool {
	return len(n.lits) > 0 || len(n.params) > 0 || n.wild != nil
}

func insert(root *tnode, rt route, skipSegs int) {
	n := root
	for _, tk := range rt.tokens[skipSegs:] {
		switch tk.kind {
		case tokLit:
			var child *tnode
			for i := range n.lits {
				if n.lits[i].seg == tk.lit {
					child = n.lits[i].child
					break
				}
			}
			if child == nil {
				child = &tnode{}
				n.lits = append(n.lits, litEdge{tk.lit, child})
			}
			n = child
		case tokParam:
			var child *tnode
			for _, pe := range n.params {
				if pe.p.name == tk.p.name && pe.p.ref == tk.p.ref && pe.p.extraArgs == tk.p.extraArgs &&
					(!tk.p.ref.method || pe.owner == rt.owner) {
					child = pe.child
					break
				}
			}
			if child == nil {
				child = &tnode{}
				n.params = append(n.params, &paramEdge{tk.p, rt.owner, child})
			}
			n = child
		case tokWild:
			name := ""
			if tk.p != nil {
				name = tk.p.name
			}
			if n.wild == nil {
				n.wild = &wildEdge{name: name}
			} else if n.wild.name != name {
				fatalf("%s: conflicting wildcard names %q and %q at the same position", rt.owner.name, n.wild.name, name)
			}
			n.wild.routes = append(n.wild.routes, rt)
			return
		}
	}
	n.routes = append(n.routes, rt)
}

type binding struct {
	name, expr string
	arg        bool // pass as a handler argument instead of SetPathValue
}

func withBinding(binds []binding, b binding) []binding {
	out := make([]binding, len(binds)+1)
	copy(out, binds)
	out[len(binds)] = b
	return out
}

type emitter struct {
	b        strings.Builder
	depth    int
	n        int
	scope    *apiType            // the dispatcher being generated (api or central)
	curOwner *apiType            // owner of the route currently being emitted
	recvOf   map[*apiType]string // receiver expression per mounted api
	hoisted  string              // method already verified by a subtree-level check
	slots    map[string]string   // per dispatcher: type[@position] -> var declared once at the top of ServeHTTP
	byType   map[string]string   // type -> the first of those, shared by results and bodies
	decls    []slotDecl          // those declarations, in first-use order, named by spliceDecls
	fixed    map[string]string   // trie variables (sN, pN, iN, mpN, miN) -> type, declared at the top under their own names
	fixedOrd []string            // fixed in first-use order
	useURL   bool                // a top-scope url.Values needs net/url
	quals    map[string]struct{} // package qualifiers the top-scope declarations name: imported
	useErr   bool                // a hoisted "err" is assigned somewhere in the dispatcher
	errVar   string              // expr for an error handler's error param ("err"/"nil")

	// ggen fast-path helpers used anywhere in the output
	useReadOne    bool
	useReadSlice  bool
	useReadSeq    bool
	useWriteOne   bool
	useWriteSlice bool
	useWriteAny   bool
	useWriteStd   bool

	useStrings bool // output calls strings.IndexByte, the only strings use left

	// buffer pool expressions: a -helpers package's exported pool, or the
	// package-local one emitted below when there isn't one
	readPool   string
	writePool  string
	localRead  bool
	localWrite bool
}

// needsReadPool reports whether anything in the output draws a read buffer.
// Writes only need one on the any path — ggen's WriteTo/WriteSliceTo carry
// their own pool for the rest.
func (g *emitter) needsReadPool() bool  { return g.useReadOne || g.useReadSlice || g.useReadSeq }
func (g *emitter) needsWritePool() bool { return g.useWriteAny }

func (g *emitter) wf(format string, args ...any) {
	g.b.WriteString(strings.Repeat("\t", g.depth))
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

func (g *emitter) openf(format string, args ...any) {
	g.wf(format, args...)
	g.depth++
}

func (g *emitter) close() {
	g.depth--
	g.wf("}")
}

// Hoisted slots: a variable per type declared once at the top of ServeHTTP,
// instead of one per route (Go never shares stack slots across switch cases).
// Only one route runs per request, so routes of a type share it. Only values
// whose address is never taken are hoisted: an escaping hoisted variable is
// heap-allocated at function entry, on every request.

// slot is the variable a (T, error) handler result of typ lands in: a path
// param slot of that type when there is one (args are evaluated before the
// result is assigned), else its own.
func (g *emitter) slot(typ string) string {
	if v, ok := g.byType[typ]; ok {
		return v
	}
	return g.declSlot(typ, typ, "", true)
}

// slotAt is the slot for a path param of typ at trie position depth: a route
// carries one param per position, so position keys the variable.
func (g *emitter) slotAt(typ string, depth int) string {
	key := typ
	if depth > 0 {
		key = fmt.Sprintf("%s@%d", typ, depth)
	}
	return g.declSlot(key, typ, "", true)
}

// bodySlot is the slot for a JSON body. Never shared with a param or a
// result: the params are still to be passed while it is decoded, and a
// handler keeping a *T body must not see its result written over it.
func (g *emitter) bodySlot(typ string) string {
	return g.declSlot("body "+typ, typ, slotName(typ)+"Body", false)
}

// bodyPtr is a top-scope *T a route points at a fresh T: a body that
// escapes anyway (kept by the handler, or decoded through an interface) is
// then allocated by that route alone, not by every request.
func (g *emitter) bodyPtr(typ string) string {
	p := g.declSlot("bodyptr "+typ, "*"+typ, slotName(typ)+"BodyPtr", false)
	g.wf("%s = new(%s)", p, typ)
	return p
}

// hintName is a handler param name usable as a variable name hint, or "".
func hintName(name string) string {
	if token.IsIdentifier(name) && !token.IsKeyword(name) && name != "_" {
		return name
	}
	return ""
}

// tmp is a top-scope variable for a route-local temporary. Routes are
// exclusive and the ordinal (g.n) resets at every route/handler emission
// entry (emitCall, notFound, notAllowed), so (role, type, ordinal) is the same
// variable in every route: the frame holds one per shape, not per route.
func (g *emitter) tmp(hint, typ string) string {
	g.n++
	return g.declSlot(fmt.Sprintf("tmp %s %s %d", hint, typ, g.n), typ, hint, false)
}

// declSlot returns a placeholder; spliceDecls names it once the whole body is
// known, so the name can avoid everything the function refers to.
func (g *emitter) declSlot(key, typ, hint string, shared bool) string {
	if v, ok := g.slots[key]; ok {
		return v
	}
	v := fmt.Sprintf("__slot%d__", len(g.decls))
	g.slots[key] = v
	if _, ok := g.byType[typ]; shared && !ok {
		g.byType[typ] = v
	}
	g.decls = append(g.decls, slotDecl{v, typ, hint})
	return v
}

type slotDecl struct{ placeholder, typ, hint string }

// fixedVar declares a trie variable at the top under its own name. Names are
// per trie depth, and depth only grows along a path, so the one variable is
// never live in two places at once.
func (g *emitter) fixedVar(name, typ string) string {
	if _, ok := g.fixed[name]; !ok {
		g.fixed[name] = typ
		g.fixedOrd = append(g.fixedOrd, name)
	}
	return name
}

func ivar(i int) string { return fmt.Sprintf("i%d", i) }

// slotName derives a variable name from a type: the bare type name with its
// first letter lowered, pluralized for a slice, so a `services.NewUser` body
// is `newUser` and `[]services.NewUser` is `newUsers`.
func slotName(typ string) string {
	name := typ
	slice := strings.HasPrefix(name, "[]")
	name = strings.TrimLeft(name, "[]*")
	if i := strings.LastIndexByte(name, '.'); i >= 0 {
		name = name[i+1:]
	}
	if i := strings.IndexByte(name, '['); i >= 0 {
		name = name[:i]
	}
	if name == "" || !unicode.IsLetter(rune(name[0])) {
		return "val"
	}
	name = strings.ToLower(name[:1]) + name[1:]
	if slice {
		name += "s"
	}
	if token.IsKeyword(name) || types.Universe.Lookup(name) != nil {
		name += "Val"
	}
	return name
}

// errSlot is the shared "err" those assignments write.
func (g *emitter) errSlot() string {
	g.useErr = true
	return errName
}

const (
	errName = "err"
	nilName = "nil"
)

// spliceDecls inserts the hoisted declarations at mark, right after the
// ServeHTTP opening brace, and names the slots. A name must not be an
// identifier the body or the slot types refer to (a package such as `user`
// for `user.User`, a helper, a handler) nor the receiver: shadowing any of
// those breaks the code that follows.
func (g *emitter) spliceDecls(mark int, recv string) {
	if len(g.decls) == 0 && len(g.fixedOrd) == 0 && !g.useErr {
		return
	}
	out := g.b.String()
	body := out[mark:]
	taken := map[string]struct{}{recv: {}, "w": {}, "r": {}}
	var refs strings.Builder
	refs.WriteString(goStringLit.ReplaceAllString(body, `""`))
	for _, d := range g.decls {
		refs.WriteString(" " + d.typ)
	}
	for _, id := range goIdent.FindAllString(refs.String(), -1) {
		taken[id] = struct{}{}
	}
	var d strings.Builder
	if g.useErr {
		d.WriteString("\tvar err error\n")
	}
	for _, name := range g.fixedOrd {
		fmt.Fprintf(&d, "\tvar %s %s\n", name, g.fixed[name])
	}
	for _, decl := range g.decls {
		if decl.typ != "url.Values" {
			for _, m := range goQual.FindAllStringSubmatch(decl.typ, -1) {
				g.quals[m[1]] = struct{}{}
			}
		}
		name := decl.hint
		if name == "" {
			name = slotName(decl.typ)
		}
		for base, n := name, 1; !safeVarName(name) || isTaken(taken, name); n++ {
			name = base + strconv.Itoa(n)
		}
		taken[name] = struct{}{}
		body = strings.ReplaceAll(body, decl.placeholder, name)
		fmt.Fprintf(&d, "\tvar %s %s\n", name, decl.typ)
	}
	g.b.Reset()
	g.b.WriteString(out[:mark])
	g.b.WriteString(d.String())
	g.b.WriteString(body)
}

func isTaken(set map[string]struct{}, name string) bool {
	_, ok := set[name]
	return ok
}

var (
	goIdent     = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)
	goQual      = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)\.`)
	goStringLit = regexp.MustCompile(`"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'`)
)

// Trie variables are named by segment position, not a counter, so generated
// output is stable under route insertions: pvar is the rest-of-path starting
// at segment i, svar the segment scanned at position i (ivar its slash index,
// next to fixedVar). All are declared once at the top; sibling branches
// assign the same one, which only they use.
func pvar(i int) string { return fmt.Sprintf("p%d", i) }
func svar(i int) string { return fmt.Sprintf("s%d", i) }

func (g *emitter) cond(p *param, recv, v string) string {
	switch {
	case p.regex:
		return p.ref.expr(recv) + ".MatchString(" + v + ")"
	case p.ref.isSet():
		return p.ref.expr(recv) + "(" + v + ")"
	default:
		return v + ` != ""`
	}
}

// emitDispatcher generates the ServeHTTP (and middleware plumbing) for one
// dispatcher: a standalone api, or an app with the routes of all its mounted
// apis merged into a single match tree.
func (g *emitter) emitDispatcher(scope *apiType, routes []route, recvOf map[*apiType]string) {
	g.n = 0
	g.scope = scope
	g.recvOf = recvOf
	g.hoisted = ""
	g.slots, g.byType, g.decls, g.useErr = map[string]string{}, map[string]string{}, nil, false
	g.fixed, g.fixedOrd = map[string]string{}, nil
	star := ""
	if scope.ptr {
		star = "*"
	}
	recv := scope.recv
	if recv == "" {
		recv = "a"
	}

	g.openf("func (%s %s%s) ServeHTTP(w http.ResponseWriter, r *http.Request) {", recv, star, scope.name)
	mark := g.b.Len()
	defer g.spliceDecls(mark, recv)
	g.curOwner = nil
	for _, mw := range scope.middlewares {
		g.emitGuard(mw, recv, nil)
	}
	g.emitXMounts(recv, scope.xmounts, 0, "r.URL.Path", 0)
	if len(routes) == 0 {
		g.notFound(false)
		g.close()
		g.wf("")
		return
	}
	prefix := gen.CommonPrefix(routePatterns(routes))

	g.wf("path := r.URL.Path")
	g.openf("if len(path) < %d || path[:%d] != %q {", len(prefix), len(prefix), prefix)
	g.notFound(false)
	g.wf("return")
	g.close()
	g.wf("path = path[%d:]", len(prefix))

	staticByPath := map[string][]route{}
	var keys []string
	var dynamic []route
	for _, rt := range routes {
		if isDynamic(rt) {
			dynamic = append(dynamic, rt)
			continue
		}
		key := rt.pattern[len(prefix):]
		if _, ok := staticByPath[key]; !ok {
			keys = append(keys, key)
		}
		staticByPath[key] = append(staticByPath[key], rt)
	}

	if len(keys) > 0 {
		slices.Sort(keys)
		cases := make([]strCase, len(keys))
		for i, k := range keys {
			cases[i] = strCase{k, func() { g.emitDispatch(staticByPath[k], nil, nil) }}
		}
		g.emitStrSwitch("path", "len(path)", cases)
	}

	exhaustive := false
	if len(dynamic) > 0 {
		root := &tnode{}
		skipSegs := strings.Count(prefix, "/") - 1
		for _, rt := range dynamic {
			insert(root, rt, skipSegs)
		}
		exhaustive = g.emitNode(root, "path", nil, 0)
	}
	if !exhaustive {
		g.notFound(true)
	}
	g.close()
	g.wf("")
}

// hasPrefix renders a constant-prefix test as a plain compare. The compiler
// expands it in place at any function size, while strings.HasPrefix/CutPrefix
// stop inlining once a dispatcher passes the inliner's big-function threshold.
func hasPrefix(v, lit string) string {
	return fmt.Sprintf("%s >= %d && %s == %q", lenExpr(v), len(lit), sliceExpr(v, "", strconv.Itoa(len(lit))), lit)
}

// Slices of slices fold into one: v[7:10] rather than v[:10][7:], and
// len(v[11:]) is len(v)-11. Only the shapes the generator itself produces
// (one constant or one identifier bound) are recognized.
var (
	reCut   = regexp.MustCompile(`^(\w+)\[(\w[\w+-]*):\]$`) // v[a:]
	reWidth = regexp.MustCompile(`^(\w+)\[:(\w[\w+-]*)\]$`) // v[:k]
)

// addExpr sums two index expressions, folding constants: "i+1" + "2" = "i+3".
func addExpr(a, b string) string {
	an, aErr := strconv.Atoi(a)
	bn, bErr := strconv.Atoi(b)
	switch {
	case aErr == nil && bErr == nil:
		return strconv.Itoa(an + bn)
	case aErr == nil:
		a = b
	case bErr == nil:
		an = bn
	default:
		return a + "+" + b
	}
	if an == 0 {
		return a
	}
	if i := strings.LastIndexByte(a, '+'); i > 0 {
		if n, err := strconv.Atoi(a[i+1:]); err == nil {
			return fmt.Sprintf("%s+%d", a[:i], n+an)
		}
	}
	return fmt.Sprintf("%s+%d", a, an)
}

// sliceExpr renders v[lo:hi] ("" = open end) with nested slices folded.
func sliceExpr(v, lo, hi string) string {
	if m := reCut.FindStringSubmatch(v); m != nil {
		if lo == "" {
			lo = "0"
		}
		lo = addExpr(lo, m[2])
		if hi != "" {
			hi = addExpr(hi, m[2])
		}
		v = m[1]
	} else if m := reWidth.FindStringSubmatch(v); m != nil {
		if hi == "" {
			hi = m[2]
		}
		v = m[1]
	}
	if lo == "0" {
		lo = ""
	}
	return fmt.Sprintf("%s[%s:%s]", v, lo, hi)
}

// indexExpr renders v[at] with a nested slice folded.
func indexExpr(v, at string) string {
	if m := reCut.FindStringSubmatch(v); m != nil {
		return fmt.Sprintf("%s[%s]", m[1], addExpr(at, m[2]))
	}
	if m := reWidth.FindStringSubmatch(v); m != nil {
		return fmt.Sprintf("%s[%s]", m[1], at)
	}
	return fmt.Sprintf("%s[%s]", v, at)
}

func lenExpr(v string) string {
	if m := reCut.FindStringSubmatch(v); m != nil {
		if _, err := strconv.Atoi(m[2]); err == nil {
			return fmt.Sprintf("len(%s)-%s", m[1], m[2])
		}
		return fmt.Sprintf("len(%s)-(%s)", m[1], m[2])
	}
	if m := reWidth.FindStringSubmatch(v); m != nil {
		return m[2]
	}
	return "len(" + v + ")"
}

// openCut opens a block entered when v starts with lit, rest holding the tail.
func (g *emitter) openCut(rest, v, lit string) {
	g.openf("if %s {", hasPrefix(v, lit))
	g.advance(rest, v, fmt.Sprintf("[%d:]", len(lit)))
}

// advance sets rest to v sliced by cut. A node whose remaining code never reads
// v again passes rest == v and moves it in place: every declared variable gets
// its own spill slot, and one per route grew a 2000-route frame to 32KB.
func (g *emitter) advance(rest, v, cut string) {
	if rest != v {
		g.fixedVar(rest, typString)
	}
	if lo, ok := strings.CutSuffix(strings.TrimPrefix(cut, "["), ":]"); ok {
		g.wf("%s = %s", rest, sliceExpr(v, lo, ""))
		return
	}
	g.wf("%s = %s%s", rest, v, cut)
}

// strCase is one literal arm of a generated string dispatch.
type strCase struct {
	key  string
	body func()
}

// hashMin (-hashmin) is the sibling count from which a literal set dispatches
// through a generated hash instead of a string switch: 0 hashes every set the
// planner can hash, -1 never. Measured crossover for the default: the hash
// always pays one mispredicted jump, so below ~256 keys skewed (Zipf) traffic
// is faster through the compiler's binary search.
var hashMin = 256

// emitStrSwitch dispatches x, whose length is the expression n ("" when the
// caller already pinned it to the keys' shared length), over literal keys. Go
// compiles a string switch to a binary search: ~log2(n) conditional branches
// that mispredict under spread-out traffic (4.6 misses a request at 2000
// routes, 1 with the hash). From hashMin keys up, the distinguishing bytes are hashed
// into a dense integer switch instead, which compiles to one jump table, and
// the key is verified inside the arm; colliding keys chain there.
func (g *emitter) emitStrSwitch(x, n string, cases []strCase) {
	plain := func(cases []strCase) {
		// the shared head goes in front of the switch, the arms compare tails
		lcp := commonHead(cases)
		if len(cases) < 4 || len(lcp) < 2 {
			lcp = ""
		}
		sw := x
		if lcp != "" {
			g.openf("if %s >= %d && %s == %q {", lenExpr(x), len(lcp), sliceExpr(x, "", strconv.Itoa(len(lcp))), lcp)
			sw = sliceExpr(x, strconv.Itoa(len(lcp)), "")
		}
		g.wf("switch %s {", sw)
		for _, c := range cases {
			g.wf("case %q:", c.key[len(lcp):])
			g.depth++
			c.body()
			g.depth--
		}
		g.wf("}")
		if lcp != "" {
			g.close()
		}
	}
	// one short key caps the byte positions every key can be read at, so the
	// shortest keys peel off into a plain switch until the rest hash well
	lens := make([]int, 0, len(cases))
	for _, c := range cases {
		lens = append(lens, len(c.key))
	}
	slices.Sort(lens)
	lens = slices.Compact(lens)
	var plan hashPlan
	var short []strCase
	ok := false
	for _, cut := range lens {
		var long []strCase
		short = short[:0]
		for _, c := range cases {
			if len(c.key) < cut {
				short = append(short, c)
			} else {
				long = append(long, c)
			}
		}
		if len(long) < max(hashMin, 2) {
			break
		}
		keys := make([]string, len(long))
		for i, c := range long {
			keys[i] = c.key
		}
		if plan, ok = planHash(keys); ok {
			cases = long
			break
		}
	}
	if !ok {
		plain(cases)
		return
	}
	switch {
	case n == "":
	case plan.minLen == plan.maxLen && len(short) == 0:
		g.openf("if %s == %d {", n, plan.minLen)
	default:
		g.openf("if %s >= %d {", n, plan.minLen)
	}
	// the keys' shared head is verified once, before the hash; each arm then
	// compares only the tail that tells its key apart
	lcp := commonHead(cases)
	if len(lcp) < 2 {
		lcp = "" // not worth a compare of its own; arms then keep the whole key
	}
	tail := x
	if lcp != "" {
		g.openf("if %s == %q {", sliceExpr(x, "", strconv.Itoa(len(lcp))), lcp)
		tail = sliceExpr(x, strconv.Itoa(len(lcp)), "")
	}
	var parts []string
	for j, p := range plan.pos {
		at := strconv.Itoa(p)
		if p < 0 {
			at = fmt.Sprintf("%s-%d", n, -p)
		}
		b := fmt.Sprintf("uint32(%s)", indexExpr(x, at))
		if j > 0 {
			b += fmt.Sprintf("<<%d", 8*j)
		}
		parts = append(parts, b)
	}
	u := strings.Join(parts, " | ")
	if plan.useLen {
		if u != "" {
			u = "(" + u + ") + "
		}
		u += fmt.Sprintf("uint32(%s)*%#x", n, uint32(hashLenMul))
	}
	g.wf("switch ((%s) * %#x) >> %d {", u, plan.mul, 32-plan.bits)
	slots := make([]uint32, 0, len(plan.slots))
	for slot := range plan.slots {
		slots = append(slots, slot)
	}
	slices.Sort(slots)
	for _, slot := range slots {
		g.wf("case %d:", slot)
		g.depth++
		for j, ci := range plan.slots[slot] {
			if j == 0 {
				g.openf("if %s == %q {", tail, cases[ci].key[len(lcp):])
			} else {
				g.depth--
				g.wf("} else if %s == %q {", tail, cases[ci].key[len(lcp):])
				g.depth++
			}
			cases[ci].body()
		}
		g.close()
		g.depth--
	}
	g.wf("}")
	if lcp != "" {
		g.close()
	}
	if n == "" {
		return
	}
	if len(short) > 0 {
		g.depth--
		g.wf("} else {")
		g.depth++
		plain(short)
	}
	g.close()
}

const hashLenMul = 0x27d4eb2f

func commonHead(cases []strCase) string {
	lcp := cases[0].key
	for _, c := range cases[1:] {
		k := 0
		for k < len(lcp) && k < len(c.key) && lcp[k] == c.key[k] {
			k++
		}
		lcp = lcp[:k]
	}
	return lcp
}

// hashPlan is a multiply-shift hash over up to four byte positions (negative =
// counted from the end) plus, when key lengths differ, the length.
type hashPlan struct {
	pos            []int
	useLen         bool
	mul            uint32
	bits           int
	minLen, maxLen int
	slots          map[uint32][]int
}

func (p *hashPlan) hash(key string) uint32 {
	var u uint32
	for j, at := range p.pos {
		if at < 0 {
			at += len(key)
		}
		u |= uint32(key[at]) << (8 * j)
	}
	if p.useLen {
		u += uint32(len(key)) * hashLenMul //nolint:gosec // route literals are tiny
	}
	return (u * p.mul) >> (32 - p.bits)
}

// planHash picks byte positions greedily by how many keys they tell apart,
// then the multiplier and table size with the shortest collision chains that
// still meet the compiler's jump table density (a quarter of the range used).
func planHash(keys []string) (hashPlan, bool) {
	var best hashPlan
	if hashMin < 0 || len(keys) < max(hashMin, 2) {
		return best, false
	}
	p := hashPlan{minLen: len(keys[0]), maxLen: len(keys[0])}
	for _, k := range keys[1:] {
		p.minLen, p.maxLen = min(p.minLen, len(k)), max(p.maxLen, len(k))
	}
	p.useLen = p.minLen != p.maxLen
	var cands []int
	for at := range p.minLen {
		cands = append(cands, at)
	}
	if p.useLen {
		for back := 1; back <= p.minLen; back++ {
			cands = append(cands, -back)
		}
	}
	sig := make([]string, len(keys))
	if p.useLen {
		for i, k := range keys {
			sig[i] = strconv.Itoa(len(k))
		}
	}
	distinct := func(extra int) int {
		seen := make(map[string]struct{}, len(keys))
		for i, k := range keys {
			at := extra
			if at < 0 {
				at += len(k)
			}
			seen[sig[i]+string(k[at])] = struct{}{}
		}
		return len(seen)
	}
	have := 1
	if p.useLen {
		seen := map[string]struct{}{}
		for _, v := range sig {
			seen[v] = struct{}{}
		}
		have = len(seen)
	}
	for len(p.pos) < 4 && have < len(keys) {
		pick, got := 0, have
		for _, c := range cands {
			if d := distinct(c); d > got {
				pick, got = c, d
			}
		}
		if got == have {
			break
		}
		for i, k := range keys {
			at := pick
			if at < 0 {
				at += len(k)
			}
			sig[i] += string(k[at])
		}
		p.pos, have = append(p.pos, pick), got
	}
	// ascending offsets let the compiler fuse adjacent bytes into one load
	slices.Sort(p.pos)

	bestChain := 0
	for bits := bitsFor(len(keys)); bits <= bitsFor(2*len(keys)); bits++ {
		for _, mul := range [...]uint32{0x9e3779b1, 0x85ebca6b, 0xc2b2ae35, 0x165667b1, 0xd3a2646d, 0xfd7046c5, 0xb55a4f09} {
			c := p
			c.bits, c.mul, c.slots = bits, mul, map[uint32][]int{}
			chain := 0
			lo, hi := ^uint32(0), uint32(0)
			for i, k := range keys {
				h := c.hash(k)
				c.slots[h] = append(c.slots[h], i)
				chain = max(chain, len(c.slots[h]))
				lo, hi = min(lo, h), max(hi, h)
			}
			// below the compiler's jump table minimums the switch is a compare
			// chain again; only -hashmin 0 asks for that
			if hashMin > 0 && (len(c.slots) < 8 || int(hi-lo)+1 > 4*len(c.slots)) {
				continue
			}
			if best.slots == nil || chain < bestChain || chain == bestChain && len(c.slots) > len(best.slots) {
				best, bestChain = c, chain
			}
		}
	}
	return best, best.slots != nil && bestChain <= 3
}

func bitsFor(n int) int {
	bits := 3
	for 1<<bits < n {
		bits++
	}
	return bits
}

// emitXMounts delegates cross-package api fields to their own ServeHTTP by
// prefix: the shared head is cut once, then a switch on the next segment picks
// the mount. A mount whose prefix ends at off goes last, so a longer one wins.
func (g *emitter) emitXMounts(recv string, xms []xmount, off int, v string, depth int) {
	var here *xmount
	var rest []xmount
	seen := map[string]struct{}{}
	for i := range xms {
		if _, dup := seen[xms[i].prefix]; dup {
			continue
		}
		seen[xms[i].prefix] = struct{}{}
		if len(xms[i].prefix) > off {
			rest = append(rest, xms[i])
		} else {
			here = &xms[i]
		}
	}
	delegate := func(xm xmount) {
		g.wf("%s.%s.ServeHTTP(w, r)", recv, xm.field)
		g.wf("return")
	}
	prefixed := func(xm xmount) {
		g.openf("if %s {", hasPrefix(v, xm.prefix[off:]))
		delegate(xm)
		g.close()
	}
	switch {
	case len(rest) == 1:
		prefixed(rest[0])
	case len(rest) > 1:
		tails := make([]string, len(rest))
		for i, xm := range rest {
			tails[i] = xm.prefix[off:]
		}
		if lcp := gen.CommonPathPrefix(tails); strings.HasSuffix(lcp, "/") {
			mp := fmt.Sprintf("mp%d", depth)
			g.openCut(mp, v, lcp)
			g.emitXMounts(recv, rest, off+len(lcp), mp, depth+1)
			g.close()
			break
		}
		bySeg := map[string][]xmount{}
		var segs []string
		for i, xm := range rest {
			j := strings.IndexByte(tails[i], '/')
			if j < 0 {
				prefixed(xm)
				continue
			}
			seg := tails[i][:j]
			if _, ok := bySeg[seg]; !ok {
				segs = append(segs, seg)
			}
			bySeg[seg] = append(bySeg[seg], xm)
		}
		slices.Sort(segs)
		if len(segs) == 0 {
			break
		}
		// equal-width segments slice fixed, the slash inside the case is the boundary
		width := len(segs[0])
		for _, seg := range segs[1:] {
			if len(seg) != width {
				width = -1
				break
			}
		}
		if width >= 0 {
			g.openf("if len(%s) > %d {", v, width)
			cases := make([]strCase, len(segs))
			for i, seg := range segs {
				cases[i] = strCase{seg + "/", func() {
					g.emitXMounts(recv, bySeg[seg], off+width+1, fmt.Sprintf("%s[%d:]", v, width+1), depth+1)
				}}
			}
			g.emitStrSwitch(fmt.Sprintf("%s[:%d]", v, width+1), "", cases)
			g.close()
			break
		}
		mi := g.fixedVar(fmt.Sprintf("mi%d", depth), "int")
		g.useStrings = true
		g.openf("if %s = strings.IndexByte(%s, '/'); %s >= 0 {", mi, v, mi)
		cases := make([]strCase, len(segs))
		for i, seg := range segs {
			cases[i] = strCase{seg, func() {
				g.emitXMounts(recv, bySeg[seg], off+len(seg)+1, v+"["+mi+"+1:]", depth+1)
			}}
		}
		g.emitStrSwitch(v+"[:"+mi+"]", mi, cases)
		g.close()
	}
	if here != nil {
		delegate(*here)
	}
}

// notFound responds 404. A handler taking an error gets err, the last path
// param conversion that failed (a later successful one resets it), when
// conversions ran before this site; nil otherwise.
func (g *emitter) notFound(converted bool) {
	g.n = 0
	if g.scope.notFound.isSet() {
		errVar := nilName
		if converted && g.useErr {
			errVar = errName
		}
		g.emitEHandler(g.scope.notFound, g.recvOf[g.scope], errVar)
	} else {
		g.wf("w.WriteHeader(http.StatusNotFound)")
	}
}

// notAllowed sets the Allow header (also for a custom handler) and responds
// 405, preferring the owning api's handler when the leaf belongs to one api.
func (g *emitter) notAllowed(routes []route, allow string) {
	g.n = 0
	target := g.scope
	if len(routes) > 0 {
		owner := routes[0].owner
		uniform := true
		for _, rt := range routes[1:] {
			if rt.owner != owner {
				uniform = false
				break
			}
		}
		if uniform && owner.notAllowed.isSet() {
			target = owner
		}
	}
	g.wf(`w.Header().Set("Allow", %q)`, allow)
	if target.notAllowed.isSet() {
		g.emitEHandler(target.notAllowed, g.recvOf[target], "")
	} else {
		g.wf("w.WriteHeader(http.StatusMethodNotAllowed)")
	}
}

// openParamCheck opens the if-block validating v against p and returns the
// binding the leaf should record. used=false discards a transformed value no
// downstream handler takes, avoiding an unused variable.
func (g *emitter) openParamCheck(pe *paramEdge, v string, used bool, depth int) binding {
	p := pe.p
	if p.transform {
		call := fmt.Sprintf("%s(%s%s)", p.ref.expr(g.recvOf[pe.owner]), v, p.extraArgs)
		val := "_"
		switch {
		case !used:
		case p.typ != "":
			// a known type parses into the dispatcher-level slot for that
			// type and position, shared with same-typed handler results
			val = g.slotAt(p.typ, depth)
		default:
			typ := paramArgType(pe.child, p.name)
			if typ == "" {
				// an external transformer and handlers disagreeing on the type:
				// nothing single to declare, so this one stays scoped. External
				// refs always return (T, error)
				val = fmt.Sprintf("t%d", depth)
				if g.scope.notFound.hasErr {
					e := fmt.Sprintf("terr%d", depth)
					g.openf("if %s, %s := %s; %s != nil {", val, e, call, e)
					g.wf("%s = %s", g.errSlot(), e)
					g.depth--
					g.wf("} else {")
					g.depth++
				} else {
					g.openf("if %s, err := %s; err == nil {", val, call)
				}
				return binding{p.name, val, true}
			}
			val = g.slotAt(typ, depth)
		}
		if p.ok {
			g.openf("if %s, %s = %s; ok {", val, g.fixedVar("ok", typBool), call)
		} else {
			g.openf("if %s, %s = %s; err == nil {", val, g.errSlot(), call)
		}
		return binding{p.name, val, true}
	}
	g.openf("if %s {", g.cond(p, g.recvOf[pe.owner], v))
	return binding{p.name, v, false}
}

// paramArgType is the type every handler below n binds path param name as,
// standing in for an external transformer's unknown result type; "" when
// they disagree.
func paramArgType(n *tnode, name string) string {
	typ := ""
	for _, rt := range subtreeRoutes(n, nil) {
		for _, spec := range rt.args {
			if spec.kind != argParam || spec.name != name || spec.typeExpr == nil {
				continue
			}
			t := renderType(token.NewFileSet(), spec.typeExpr)
			if typ != "" && t != typ {
				return ""
			}
			typ = t
		}
	}
	return typ
}

// routesUse reports whether any of rts takes the path param as an argument.
func routesUse(rts []route, name string) bool {
	for _, rt := range rts {
		for _, spec := range rt.args {
			if spec.kind == argParam && spec.name == name {
				return true
			}
		}
	}
	return false
}

// subtreeUsesPath reports whether any route at or below n takes the path
// param as a handler argument.
func subtreeUsesPath(n *tnode, name string) bool {
	return routesUse(n.routes, name) || belowUsesPath(n, name)
}

// belowUsesPath is subtreeUsesPath without n's own terminal routes. Those are
// emitted by n's parent against the parent's variable, so they say nothing
// about a variable handed to emitNode(n).
func belowUsesPath(n *tnode, name string) bool {
	for _, e := range n.lits {
		if subtreeUsesPath(e.child, name) {
			return true
		}
	}
	for _, pe := range n.params {
		if subtreeUsesPath(pe.child, name) {
			return true
		}
	}
	return n.wild != nil && routesUse(n.wild.routes, name)
}

// readsRest reports whether emitNode(n, v) reads v. n's own terminal routes
// don't count (see belowUsesPath), and a catch-all reads it only when its
// value lands somewhere.
func readsRest(n *tnode) bool {
	switch {
	case len(n.lits)+len(n.params) > 0:
		return true
	case n.wild == nil || n.wild.name == "":
		return false
	case !noPathValue:
		return true
	}
	return routesUse(n.wild.routes, n.wild.name)
}

// emitNode generates matching code for one trie node. Reports whether it
// ends in an unconditional dispatch (a wildcard), making later code dead.
//
// A node does at most one IndexByte to split the rest of the path into
// "final segment" vs "more segments follow"; sibling literals in each half
// dispatch through a switch on that segment.
func (g *emitter) emitNode(n *tnode, cur string, binds []binding, depth int) bool {
	// when every route below shares one method, verify it once at the top of
	// the branch instead of per leaf (method mismatch then wins over a
	// deeper structural mismatch: 405, not 404)
	if g.hoistMethod(n) {
		defer func() { g.hoisted = "" }()
	}

	// lone literal chain: a single comparison, no segment scan
	if len(n.lits) == 1 && len(n.params) == 0 && n.wild == nil {
		seg, child := compress(n.lits[0])
		term := len(child.routes) > 0
		next := depth + strings.Count(seg, "/") + 1
		switch {
		case term && !child.hasDesc():
			g.openf("if %s == %q {", cur, seg)
			g.emitLeaf(child.routes, binds)
			g.close()
		case !term:
			v := cur
			if readsRest(child) {
				g.openCut(v, cur, seg+"/")
			} else {
				g.openf("if %s {", hasPrefix(cur, seg+"/"))
			}
			g.emitNode(child, v, binds, next)
			g.close()
		default:
			v := cur
			g.openCut(v, cur, seg)
			g.openf(`if %s == "" {`, v)
			g.emitLeaf(child.routes, binds)
			g.close()
			if readsRest(child) {
				g.openCut(v, v, "/")
			} else {
				g.openf("if %s {", hasPrefix(v, "/"))
			}
			g.emitNode(child, v, binds, next)
			g.close()
			g.close()
		}
		return false
	}

	// constrained params are more specific: try them before catch-any ones
	// (auto-derived transformers like Atoi count as constraints too), and
	// bools after numerics so ParseBool's lax "1"/"0" never claim a digit
	constrained := func(p *param) bool { return p.checker != "" || p.ref.isSet() }
	rank := func(p *param) int {
		switch {
		case !constrained(p):
			return 3
		case p.class == classBool:
			return 2
		default:
			return 1
		}
	}
	slices.SortStableFunc(n.params, func(a, b *paramEdge) int {
		return rank(a.p) - rank(b.p)
	})

	// several params may share a position when their matchers differ: they
	// are tried in declaration order, catch-any last. Reject the provably
	// ambiguous shapes.
	for i, pe := range n.params {
		for _, pe2 := range n.params[i+1:] {
			// edges only compete when both can claim the same branch: a
			// final-segment param and a more-segments-follow param coexist
			terms := len(pe.child.routes) > 0 && len(pe2.child.routes) > 0
			descs := pe.child.hasDesc() && pe2.child.hasDesc()
			if !terms && !descs {
				continue
			}
			p1, p2 := pe.p, pe2.p
			why := ""
			switch {
			case p1.ref == p2.ref && (!p1.ref.method || pe.owner == pe2.owner):
				if p1.ref.isSet() {
					why = "a matcher; the second can never match"
				} else {
					why = "the whole segment space; both match anything"
				}
			case p1.class == classNumeric && p2.class == classNumeric:
				why = "the numeric segment space; every int is also a valid float"
			case p1.class == classBool && p2.class == classBool:
				why = "the bool segment space"
			}
			if why != "" {
				fatalf("params {%s} (%s) and {%s} (%s) share a position and %s; give them non-overlapping types or matchers",
					p1.name, pe.owner.name, p2.name, pe2.owner.name, why)
			}
		}
	}

	var termLits, descLits []litEdge
	for _, e := range n.lits {
		if len(e.child.routes) > 0 {
			termLits = append(termLits, e)
		}
		if e.child.hasDesc() {
			descLits = append(descLits, e)
		}
	}
	var termParams, descParams []*paramEdge
	for _, pe := range n.params {
		if len(pe.child.routes) > 0 {
			termParams = append(termParams, pe)
		}
		if pe.child.hasDesc() {
			descParams = append(descParams, pe)
		}
	}

	emitTerm := func() {
		switch len(termLits) {
		case 0:
		case 1:
			g.openf("if %s == %q {", cur, termLits[0].seg)
			g.emitLeaf(termLits[0].child.routes, binds)
			g.close()
		default:
			cases := make([]strCase, len(termLits))
			for i, e := range termLits {
				cases[i] = strCase{e.seg, func() { g.emitLeaf(e.child.routes, binds) }}
			}
			g.emitStrSwitch(cur, "len("+cur+")", cases)
		}
		for _, pe := range termParams {
			b := g.openParamCheck(pe, cur, routesUse(pe.child.routes, pe.p.name), depth)
			g.emitLeaf(pe.child.routes, withBinding(binds, b))
			g.close()
		}
	}
	// descLits of one width with no param or wildcard sibling need no segment
	// scan: the slash is checked at a constant offset and the switch slices
	// fixed. A terminal param forces the scan, and the slices must then follow
	// its i, not the width.
	width := -1
	if len(descLits) > 1 && len(descParams) == 0 && len(termParams) == 0 && n.wild == nil {
		width = len(descLits[0].seg)
		for _, e := range descLits[1:] {
			if len(e.seg) != width {
				width = -1
				break
			}
		}
	}
	iv := ivar(depth)
	emitDesc := func() {
		descend := func(e litEdge) {
			// gate the method before even slicing the rest of the path
			hoisted := g.hoistMethod(e.child)
			v := cur
			if len(descParams) > 0 || n.wild != nil {
				v = pvar(depth + 1)
			}
			if readsRest(e.child) {
				if width >= 0 {
					g.advance(v, cur, fmt.Sprintf("[%d:]", width+1))
				} else {
					g.advance(v, cur, "["+iv+"+1:]")
				}
			}
			g.emitNode(e.child, v, binds, depth+1)
			if hoisted {
				g.hoisted = ""
			}
		}
		switch len(descLits) {
		case 0:
		case 1:
			g.openf("if %s[:%s] == %q {", cur, iv, descLits[0].seg)
			descend(descLits[0])
			g.close()
		default:
			cases := make([]strCase, len(descLits))
			for i, e := range descLits {
				cases[i] = strCase{e.seg, func() { descend(e) }}
			}
			if width >= 0 {
				g.emitStrSwitch(fmt.Sprintf("%s[:%d]", cur, width), "", cases)
			} else {
				g.emitStrSwitch(cur+"[:"+iv+"]", iv, cases)
			}
		}
		if len(descParams) > 0 {
			seg := svar(depth)
			used := !noPathValue
			for _, pe := range descParams {
				used = used || constrained(pe.p) || belowUsesPath(pe.child, pe.p.name)
			}
			if used {
				g.wf("%s = %s[:%s]", g.fixedVar(seg, typString), cur, iv)
			}
			// candidates each followed by one distinct terminal literal: switch
			// on the literal and run only that candidate's validator, instead
			// of parsing the segment once per candidate before looking past it
			if lits := terminalLits(descParams); lits != nil {
				g.wf("switch %s {", sliceExpr(cur, iv+"+1", ""))
				for k, pe := range descParams {
					g.wf("case %q:", lits[k])
					g.depth++
					b := binding{pe.p.name, seg, false}
					if constrained(pe.p) {
						b = g.openParamCheck(pe, seg, subtreeUsesPath(pe.child, pe.p.name), depth)
						g.emitLeaf(pe.child.lits[0].child.routes, withBinding(binds, b))
						g.close()
					} else {
						g.emitLeaf(pe.child.lits[0].child.routes, withBinding(binds, b))
					}
					g.depth--
				}
				g.wf("}")
				return
			}
			for k, pe := range descParams {
				b := binding{pe.p.name, seg, false}
				wrapped := constrained(pe.p) // i > 0 already guarantees a non-empty segment
				if wrapped {
					b = g.openParamCheck(pe, seg, belowUsesPath(pe.child, pe.p.name), depth)
				}
				rest := cur
				if k < len(descParams)-1 || n.wild != nil {
					rest = pvar(depth + 1)
				}
				if readsRest(pe.child) {
					g.advance(rest, cur, "["+iv+"+1:]")
				}
				g.emitNode(pe.child, rest, withBinding(binds, b), depth+1)
				if wrapped {
					g.close()
				}
			}
		}
	}

	hasTerm := len(termLits)+len(termParams) > 0
	hasDesc := len(descLits)+len(descParams) > 0
	// terminal literals compare whole, so they need no "no slash" guard; only
	// a terminal param (catch-any, or a matcher that could span a slash) does
	termScan := len(termParams) > 0
	fixedDesc := func() {
		g.openf("if len(%s) > %d && %s[%d] == '/' {", cur, width, cur, width)
		emitDesc()
		g.close()
	}
	switch {
	case hasTerm && hasDesc && !termScan && width >= 0:
		emitTerm()
		fixedDesc()
	case hasTerm && hasDesc:
		g.useStrings = true
		g.openf("if %s = strings.IndexByte(%s, '/'); %s < 0 {", g.fixedVar(iv, "int"), cur, iv)
		emitTerm()
		g.depth--
		g.wf("} else if %s > 0 {", iv)
		g.depth++
		emitDesc()
		g.close()
	case hasTerm && !termScan:
		emitTerm()
	case hasTerm:
		g.useStrings = true
		g.openf("if strings.IndexByte(%s, '/') < 0 {", cur)
		emitTerm()
		g.close()
	case hasDesc && width >= 0:
		fixedDesc()
	case hasDesc:
		g.useStrings = true
		g.openf("if %s = strings.IndexByte(%s, '/'); %s > 0 {", g.fixedVar(iv, "int"), cur, iv)
		emitDesc()
		g.close()
	}

	if n.wild != nil {
		b := binds
		if n.wild.name != "" {
			b = withBinding(binds, binding{n.wild.name, cur, false})
		}
		g.emitLeaf(n.wild.routes, b)
		return true
	}
	return false
}

// terminalLits reports the literal each candidate is followed by when every
// candidate's subtree is exactly one terminal literal and no two share one.
// Distinct literals make the candidates mutually exclusive, so dispatching on
// the literal first preserves their order.
func terminalLits(pes []*paramEdge) []string {
	lits := make([]string, len(pes))
	seen := make(map[string]struct{}, len(pes))
	for k, pe := range pes {
		c := pe.child
		if len(c.lits) != 1 || len(c.params) > 0 || c.wild != nil || len(c.routes) > 0 {
			return nil
		}
		lc := c.lits[0].child
		if len(lc.routes) == 0 || lc.hasDesc() {
			return nil
		}
		if _, dup := seen[c.lits[0].seg]; dup {
			return nil
		}
		seen[c.lits[0].seg] = struct{}{}
		lits[k] = c.lits[0].seg
	}
	return lits
}

// compress folds chains of single-literal-child nodes into one multi-segment
// literal so the prefix is matched with a single comparison.
func compress(e litEdge) (string, *tnode) {
	seg, child := e.seg, e.child
	for len(child.routes) == 0 && child.wild == nil && len(child.params) == 0 && len(child.lits) == 1 {
		seg = seg + "/" + child.lits[0].seg
		child = child.lits[0].child
	}
	return seg, child
}

// emitLeaf dispatches by method; bindings travel along so the selected
// route can bind them as args or path values.
func (g *emitter) emitLeaf(routes []route, binds []binding) {
	args := map[string]string{}
	for _, b := range binds {
		args[b.name] = b.expr
	}
	g.emitDispatch(routes, args, binds)
}

func (g *emitter) emitDispatch(routes []route, args map[string]string, binds []binding) {
	var catch *route
	var methods []route
	seen := map[string]*apiType{}
	for i := range routes {
		rt := &routes[i]
		if rt.method == "" {
			if catch != nil {
				fatalf("conflicting catch-all routes for %q (%s and %s)", rt.pattern, catch.owner.name, rt.owner.name)
			}
			catch = rt
			continue
		}
		if prev := seen[rt.method]; prev != nil {
			fatalf("conflicting routes %s %q (%s and %s)", rt.method, rt.pattern, prev.name, rt.owner.name)
		}
		seen[rt.method] = rt.owner
		methods = append(methods, *rt)
	}
	switch {
	case catch != nil && len(methods) == 0:
		g.emitCall(*catch, args, binds)
	case catch != nil && len(methods) == 1:
		g.openf("if r.Method == %q {", methods[0].method)
		g.emitCall(methods[0], args, binds)
		g.depth--
		g.wf("} else {")
		g.depth++
		g.emitCall(*catch, args, binds)
		g.close()
	case catch == nil && len(methods) == 1:
		if methods[0].method != g.hoisted {
			g.openf("if r.Method != %q {", methods[0].method)
			g.notAllowed(routes, methods[0].method)
			g.wf("return")
			g.close()
		}
		g.emitCall(methods[0], args, binds)
	default:
		g.wf("switch r.Method {")
		for _, m := range methods {
			g.wf("case %q:", m.method)
			g.depth++
			g.emitCall(m, args, binds)
			g.depth--
		}
		g.wf("default:")
		g.depth++
		if catch != nil {
			g.emitCall(*catch, args, binds)
		} else {
			allow := make([]string, len(methods))
			for i, m := range methods {
				allow[i] = m.method
			}
			g.notAllowed(routes, strings.Join(allow, ", "))
		}
		g.depth--
		g.wf("}")
	}
	g.wf("return")
}

// emitCall invokes the handler. In an app dispatcher, a route whose owning
// api declares middleware gets it wrapped around just this call.
func (g *emitter) emitCall(rt route, args map[string]string, binds []binding) {
	g.n = 0
	g.wf("r.Pattern = %q", rt.display)
	// every string param lands in PathValue: it is the request's public match
	// metadata, argument binding or not; transformed values have no raw string
	for _, b := range binds {
		if b.arg || noPathValue {
			continue
		}
		g.wf("r.SetPathValue(%q, %s)", b.name, b.expr)
	}
	owner := rt.owner
	g.curOwner = owner
	recv := g.recvOf[owner]
	if owner != g.scope {
		for _, mw := range owner.middlewares {
			g.emitGuard(mw, recv, &rt)
		}
	}
	g.emitCallBare(rt, args, recv)
}

// subtreeRoutes collects every route reachable below n, wildcards included.
func subtreeRoutes(n *tnode, out []route) []route {
	out = append(out, n.routes...)
	if n.wild != nil {
		out = append(out, n.wild.routes...)
	}
	for _, e := range n.lits {
		out = subtreeRoutes(e.child, out)
	}
	for _, pe := range n.params {
		out = subtreeRoutes(pe.child, out)
	}
	return out
}

// hoistMethod emits one method gate for a method-uniform subtree; leaves
// under it skip their own checks. Caller clears g.hoisted afterwards.
func (g *emitter) hoistMethod(n *tnode) bool {
	if g.hoisted != "" {
		return false
	}
	rts := subtreeRoutes(n, nil)
	if len(rts) == 0 || rts[0].method == "" {
		return false
	}
	m := rts[0].method
	for _, rt := range rts[1:] {
		if rt.method != m {
			return false
		}
	}
	g.openf("if r.Method != %q {", m)
	g.notAllowed(rts, m)
	g.wf("return")
	g.close()
	g.hoisted = m
	return true
}

// emitGuard emits one middleware call: a false bool return means the guard
// wrote the response, an error goes to the error handler in scope.
func (g *emitter) emitGuard(mw middleware, recv string, rt *route) {
	call := fmt.Sprintf("%s(%s)", mw.ref.expr(recv), g.buildArgs(mw.args, nil, recv))
	if mw.retErr {
		g.openf("if %s = %s; err != nil {", g.errSlot(), call)
		switch {
		case rt != nil:
			g.emitOnErr(*rt)
		case g.scope.errHandler.isSet():
			g.emitEHandler(g.scope.errHandler, g.recvOf[g.scope], errName)
		default:
			fatalf("%s: middleware returns error but there is no onerror in scope", g.scope.name)
		}
		g.wf("return")
		g.close()
	} else {
		g.openf("if !%s {", call)
		g.wf("return")
		g.close()
	}
}

// buildArgs emits the extraction preamble for the given arg specs and
// returns the call argument list.
func (g *emitter) buildArgs(specs []argSpec, args map[string]string, recv string) string {
	qv := ""
	query := func() string {
		if qv == "" {
			qv = g.tmp("values", "url.Values")
			g.useURL = true
			g.wf("%s = r.URL.Query()", qv)
		}
		return qv
	}
	var parts []string
	for _, spec := range specs {
		switch spec.kind {
		case argWriter:
			parts = append(parts, "w")
		case argWriterCast:
			parts = append(parts, fmt.Sprintf("w.(%s)", spec.typ))
		case argRequest:
			parts = append(parts, "r")
		case argContext:
			parts = append(parts, "r.Context()")
		case argError:
			parts = append(parts, g.errVar)
		case argParam:
			parts = append(parts, args[spec.name])
		case argBody:
			parts = append(parts, g.emitBodyDecode(spec))
		case argQuery:
			switch spec.bind {
			case bindParser:
				parts = append(parts, g.emitParser(spec, query(), recv))
			case bindScalar:
				parts = append(parts, g.emitExtract(spec, fmt.Sprintf("%s.Get(%q)", query(), spec.name), recv))
			default:
				parts = append(parts, g.emitQueryBind(spec, query()))
			}
		case argHeader:
			switch spec.bind {
			case bindParser:
				parts = append(parts, g.emitParser(spec, "r.Header", recv))
			case bindValues: // http.Header passthrough
				parts = append(parts, "r.Header")
			case bindStruct:
				parts = append(parts, g.emitStructBind(spec, "r.Header.Get"))
			default: // single value
				parts = append(parts, g.emitExtract(spec, fmt.Sprintf("r.Header.Get(%q)", spec.name), recv))
			}
		}
	}
	return strings.Join(parts, ", ")
}

func (g *emitter) emitCallBare(rt route, args map[string]string, recv string) {
	call := fmt.Sprintf("%s.%s(%s)", recv, rt.handler, g.buildArgs(rt.args, args, recv))
	switch rt.retKind {
	case retNone:
		g.wf("%s", call)
	case retErr:
		g.openf("if %s = %s; err != nil {", g.errSlot(), call)
		g.emitOnErr(rt)
		g.close()
	case retVal:
		if rt.enc != ggNone {
			g.emitFastEncode(rt, call)
			return
		}
		g.useWriteStd = true
		g.wf("writeJSON(w, %s)", call)
	case retValErr:
		v := g.slot(rt.retTyp)
		g.wf("%s, %s = %s", v, g.errSlot(), call)
		g.openf("if err != nil {")
		g.emitOnErr(rt)
		g.wf("return")
		g.close()
		if rt.enc != ggNone {
			g.emitFastEncode(rt, v)
			return
		}
		g.useWriteStd = true
		g.wf("writeJSON(w, %s)", v)
	}
}

// emitFastEncode writes the value through a pooled buffer; only encode errors
// surface, and they arrive before anything hit the wire, so they route through
// the same owner→central onerror chain (bare 500 if none is in scope).
//
// Marshalers go straight to ggen's WriteTo/WriteSliceTo, which own the
// buffer pool — one per process instead of one per generated package. They
// write bare, so Content-Type is stamped here, before the call.
func (g *emitter) emitFastEncode(rt route, v string) {
	var call string
	switch rt.enc {
	case ggSlice:
		g.useWriteSlice = true
		call = fmt.Sprintf("ggen.WriteSliceTo(w, %s)", v)
	case ggAny:
		g.useWriteAny = true
		call = fmt.Sprintf("writeJSONAny(w, %s)", v)
	default:
		g.useWriteOne = true
		call = fmt.Sprintf("ggen.WriteTo(w, %s)", v)
	}
	if rt.enc != ggAny {
		g.wf(`w.Header()["Content-Type"] = __jsonCT`)
	}
	g.openf("if %s = %s; err != nil {", g.errSlot(), call)
	if h, recv, ok := g.routeErrH(rt); ok {
		g.emitEHandler(h, recv, errName)
	} else {
		g.wf("w.WriteHeader(http.StatusInternalServerError)")
	}
	g.wf("return")
	g.close()
}

// routeErrH picks a route's onerror: owner first, then the dispatcher scope
// (a central's onerror covers mounted apis). ok=false → no handler in scope.
func (g *emitter) routeErrH(rt route) (ehandler, string, bool) {
	if rt.errH.isSet() {
		return rt.errH, g.recvOf[rt.owner], true
	}
	if g.scope.errHandler.isSet() {
		return g.scope.errHandler, g.recvOf[g.scope], true
	}
	return ehandler{}, "", false
}

// emitEHandler emits a call to a bound error/condition handler; errVar fills
// its error param slot ("err" in scope, "nil" for plain-bad, "" when absent).
func (g *emitter) emitEHandler(h ehandler, recv, errVar string) {
	g.errVar = errVar
	g.wf("%s(%s)", h.ref.expr(recv), g.buildArgs(h.args, nil, recv))
	g.errVar = ""
}

// emitOnErr emits a route's onerror call with err in scope, or fatals.
func (g *emitter) emitOnErr(rt route) {
	h, recv, ok := g.routeErrH(rt)
	if !ok {
		fatalf("%s.%s returns error but no onerror in scope of %s", rt.owner.name, rt.handler, g.scope.name)
	}
	g.emitEHandler(h, recv, errName)
}

// emitParser calls a whole-input parser; a bare-T parser inlines into the
// call, a (T, error) one gets a temp and a 400 check.
func (g *emitter) emitParser(spec argSpec, input, recv string) string {
	fn := spec.ref.expr(recv)
	if !spec.transform {
		return fn + "(" + input + ")"
	}
	v := g.tmp(hintName(spec.name), spec.typ)
	g.wf("%s, %s = %s(%s)", v, g.errSlot(), fn, input)
	g.openf("if err != nil {")
	g.badRequest(true)
	g.close()
	return v
}

// emitQueryBind materializes a whole-query binding (values, map or struct)
// and returns the variable to pass to the handler.
func (g *emitter) emitQueryBind(spec argSpec, q string) string {
	switch spec.bind {
	case bindValues:
		return q
	case bindMap:
		vt := typString
		if spec.mapAny {
			vt = "any"
		}
		v := g.tmp(hintName(spec.name), "map[string]"+vt)
		k, vs := g.tmp("k", typString), g.tmp("vs", "[]string")
		g.wf("%s = make(map[string]%s, len(%s))", v, vt, q)
		g.openf("for %s, %s = range %s {", k, vs, q)
		g.wf("%s[%s] = %s[0]", v, k, vs)
		g.close()
		return v
	default: // bindStruct
		return g.emitStructBind(spec, q+".Get")
	}
}

// emitStructBind fills a struct from string-keyed source, getter being the
// call prefix (e.g. "p1.Get" for query, "r.Header.Get" for headers), so the
// field reads become getter("key").
func (g *emitter) emitStructBind(spec argSpec, getter string) string {
	// absent fields keep the zero value: a temp shared with an earlier bind in
	// the same request (a central guard's) must not hand its fields over
	v := g.tmp(hintName(spec.name), spec.typ)
	g.wf("%s = %s{}", v, spec.typ)
	for _, fd := range spec.fields {
		switch fd.kind {
		case fString:
			g.wf("%s.%s = %s(%q)", v, fd.name, getter, fd.key)
		default:
			fn := "strconv.Atoi"
			if fd.kind == fBool {
				fn = "strconv.ParseBool"
			}
			rv := g.tmp("raw", typString)
			g.openf(`if %s = %s(%q); %s != "" {`, rv, getter, fd.key, rv)
			g.openf("if %s.%s, %s = %s(%s); err != nil {", v, fd.name, g.errSlot(), fn, rv)
			g.badRequest(true)
			g.close()
			g.close()
		}
	}
	return v
}

// badRequest responds 400 through the owning api's handler, the dispatcher's,
// or a bare status write; no body by default. hasErr says whether an err
// variable is in scope at the call site — a 3-arg handler gets it, or nil
// when the request is just bad without a specific error.
func (g *emitter) badRequest(hasErr bool) {
	target := g.scope
	if g.curOwner != nil && g.curOwner.badReq.isSet() {
		target = g.curOwner
	}
	if !target.badReq.isSet() {
		g.wf("w.WriteHeader(http.StatusBadRequest)")
		g.wf("return")
		return
	}
	errVar := nilName // no specific error at this site (e.g. a checker reject)
	if hasErr {
		errVar = errName
	}
	g.emitEHandler(target.badReq, g.recvOf[target], errVar)
	g.wf("return")
}

// emitBodyDecode declares the body value, decodes JSON into it (a failure is
// a 400), and returns the expression to pass. Types with ggen-generated
// methods stream-decode through a pooled buffer; the stream path copies
// strings out, so the buffer recycles immediately.
func (g *emitter) emitBodyDecode(spec argSpec) string {
	switch spec.bodyKind {
	case bodyMultipart:
		g.openf("if %s = r.ParseMultipartForm(32 << 20); err != nil {", g.errSlot())
		g.badRequest(true)
		g.close()
		if spec.ptr {
			return "r.MultipartForm"
		}
		return "*r.MultipartForm"
	case bodyForm:
		g.openf("if %s = r.ParseForm(); err != nil {", g.errSlot())
		g.badRequest(true)
		g.close()
		return "r.PostForm"
	}
	switch spec.fast {
	case ggOne:
		g.useReadOne = true
		if spec.ptr && spec.keeps {
			p := g.bodyPtr(spec.typ)
			g.wf("%s, %s = readJSON[%s](r)", "*"+p, g.errSlot(), spec.typ)
			g.openf("if err != nil {")
			g.badRequest(true)
			g.close()
			return p
		}
		v := g.bodySlot(spec.typ)
		g.wf("%s, %s = readJSON[%s](r)", v, g.errSlot(), spec.typ)
		g.openf("if err != nil {")
		g.badRequest(true)
		g.close()
		if spec.ptr {
			return "&" + v
		}
		return v
	case ggSlice:
		g.useReadSlice = true
		v := g.bodySlot("[]" + spec.elem)
		g.wf("%s, %s = readJSONSlice[%s](r)", v, g.errSlot(), spec.elem)
		g.openf("if err != nil {")
		g.badRequest(true)
		g.close()
		return v
	case ggSeq:
		// nothing is read until the handler ranges, so its errors are the handler's
		g.useReadSeq = true
		return fmt.Sprintf("readJSONSeq[%s](r)", spec.elem)
	}
	// Decode takes an interface, so its target always escapes: decode into a
	// fresh value allocated by this route alone, held by a top-scope pointer
	p := g.bodyPtr(spec.typ)
	g.openf("if %s = json.NewDecoder(r.Body).Decode(%s); err != nil {", g.errSlot(), p)
	g.badRequest(true)
	g.close()
	if spec.ptr {
		return p
	}
	return "*" + p
}

// emitExtract turns a raw query/header expression into the handler argument:
// passed through as-is, validated (false is a 400), or transformed (a missing
// value stays the zero value, an invalid one is a 400, with a nil error for a
// (T, bool) transformer).
func (g *emitter) emitExtract(spec argSpec, raw, recv string) string {
	if spec.checker == "" {
		return raw
	}
	fn := spec.ref.expr(recv)
	if !spec.transform {
		if spec.regex {
			fn += ".MatchString"
		}
		v := g.tmp("raw", typString)
		g.wf("%s = %s", v, raw)
		g.openf("if !%s(%s) {", fn, v)
		g.badRequest(false)
		g.close()
		return v
	}
	// an absent value stays the zero value, also when an earlier extract in
	// the same request (a central guard's) assigned this temp
	v := g.tmp(hintName(spec.name), spec.typ)
	g.wf("%s = *new(%s)", v, spec.typ)
	rv := g.tmp("raw", typString)
	g.openf("if %s = %s; %s != \"\" {", rv, raw, rv)
	if spec.ok {
		g.openf("if %s, %s = %s(%s); !ok {", v, g.fixedVar("ok", typBool), fn, rv)
	} else {
		g.openf("if %s, %s = %s(%s); err != nil {", v, g.errSlot(), fn, rv)
	}
	g.badRequest(!spec.ok)
	g.close()
	g.close()
	return v
}

// safeVarName reports whether the handler's own param name can be reused in
// generated code without clashing with router locals.
func safeVarName(v string) bool {
	switch v {
	case "", "_", "w", "r", "path", "err", "ok", "i":
		return false
	}
	switch v[0] {
	case 'p', 's', 't', 'v':
		if len(v) > 1 && strings.TrimLeft(v[1:], "0123456789") == "" {
			return false
		}
	}
	return true
}

// pooled-buffer JSON helpers, emitted once per output when a fast path is used
// readJSON stream-decodes a request body through a pooled buffer. The stream
// path copies strings out, so the buffer recycles immediately.
const helperReadJSON = `func readJSON[T ggen.StreamDecoder[T]](r *http.Request) (T, error) {
	bp := %s.Get().(*[]byte)
	defer %s.Put(bp)
	var s ggen.Stream
	s.Reset(r.Body, *bp)
	var zero T
	v, err := zero.DecodeFromStream(&s)
	*bp = s.Bytes()
	return v, err
}

`

// readJSONSlice stream-decodes a JSON array body through a pooled buffer.
const helperReadJSONSlice = `func readJSONSlice[T ggen.StreamDecoder[T]](r *http.Request) ([]T, error) {
	bp := %s.Get().(*[]byte)
	defer %s.Put(bp)
	var s ggen.Stream
	vs, err := s.Reset(r.Body, *bp).Slice[T]()
	*bp = s.Bytes()
	return vs, err
}

`

// readJSONSeq reads a JSON array body an element at a time, as the handler
// ranges over it. The buffer is drawn when the range starts and recycled when
// it ends, so a sequence the handler never ranges over costs nothing.
const helperReadJSONSeq = `func readJSONSeq[T ggen.StreamDecoder[T]](r *http.Request) iter.Seq2[T, error] {
	return func(yield func(T, error) bool) {
		bp := %s.Get().(*[]byte)
		defer %s.Put(bp)
		var s ggen.Stream
		for v, err := range s.Reset(r.Body, *bp).Array[T]() {
			if !yield(v, err) {
				break
			}
		}
		*bp = s.Bytes()
	}
}

`

// Content-Type is stamped by direct map assignment of one shared slice:
// Header.Set canonicalizes the key (a byte-validating walk over all 12) and
// allocates a fresh []string per response, together ~30% of a small JSON
// reply's CPU. The key is already canonical; net/http never appends to the
// value slice in place.
const helperJSONCT = `var __jsonCT = []string{"application/json"}

`

// writeJSON is the encoding/json write path. It is a function, not inline
// code: json.NewEncoder inlines and its Encoder stays on the stack, and the
// compiler gives every route's copy its own 120 byte slot — 780 routes made a
// 91KB ServeHTTP frame.
const helperWriteJSON = `func writeJSON(w http.ResponseWriter, v any) {
	w.Header()["Content-Type"] = __jsonCT
	_ = json.NewEncoder(w).Encode(v)
}

`

// writeJSONAny writes values without generated methods (maps, mixed types).
// ggen has no pooled AppendAny writer, so this is the one write path that
// still needs a buffer of its own.
const helperWriteJSONAny = `func writeJSONAny(w http.ResponseWriter, v any) error {
	bp := %s.Get().(*[]byte)
	defer %s.Put(bp)
	b, err := ggen.AppendAny((*bp)[:0], v)
	*bp = b
	if err != nil {
		return err
	}
	w.Header()["Content-Type"] = __jsonCT
	_, _ = w.Write(b)
	return nil
}

`

