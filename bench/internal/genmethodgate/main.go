// Command genmethodgate writes matched-size uniform- and mixed-method subtrees.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	count := flag.Int("count", 100, "routes per subtree")
	out := flag.String("out", "routes.go", "output file")
	flag.Parse()

	var b strings.Builder
	b.WriteString("// Code generated by internal/genmethodgate. DO NOT EDIT.\n\npackage methodgate\n\n")
	b.WriteString("import \"github.com/sirkostya009/rr/bench/internal/stress\"\n\n")
	b.WriteString("type API struct{}\n\nvar Routes = []stress.Route{\n")
	for _, group := range []string{"uniform", "mixed"} {
		for i := 0; i < *count; i++ {
			method := "GET"
			if group == "mixed" && i%2 == 1 {
				method = "POST"
			}
			pattern := fmt.Sprintf("/api/v1/%s/resource-%03d/{itemId}", group, i)
			fmt.Fprintf(&b, "\t{Pattern: %s, Method: %s, Param: \"itemId\"},\n", strconv.Quote(pattern), strconv.Quote(method))
		}
	}
	b.WriteString("}\n\n")
	for _, group := range []string{"uniform", "mixed"} {
		groupName := "Uniform"
		if group == "mixed" {
			groupName = "Mixed"
		}
		for i := 0; i < *count; i++ {
			method := "GET"
			if group == "mixed" && i%2 == 1 {
				method = "POST"
			}
			fmt.Fprintf(&b, "//rr:route %s /api/v1/%s/resource-%03d/{itemId}\nfunc (a *API) %s%03d() {}\n\n", method, group, i, groupName, i)
		}
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		panic(err)
	}
}
