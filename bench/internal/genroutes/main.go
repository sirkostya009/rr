// Command genroutes writes plausible gateway route surfaces for the scale and
// static-near-miss benchmark packages. The output is deterministic and is then
// fed to rr's normal generator by each package's go:generate directives.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	kind := flag.String("kind", "scale", "fixture kind: scale or static")
	count := flag.Int("count", 50, "number of generated routes")
	pkg := flag.String("package", "scale50", "output package name")
	out := flag.String("out", "routes.go", "output file")
	flag.Parse()
	if *count < 1 {
		panic("count must be positive")
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/genroutes. DO NOT EDIT.\n\npackage %s\n\n", *pkg)
	b.WriteString("import \"github.com/sirkostya009/rr/bench/internal/stress\"\n\n")
	b.WriteString("type API struct{}\n\n")
	fmt.Fprintf(&b, "const RouteCount = %d\n\n", *count)
	b.WriteString("var Routes = []stress.Route{\n")
	for i := 0; i < *count; i++ {
		pattern := routePattern(*kind, i)
		param := "resourceId"
		if *kind == "static" {
			param = ""
		}
		fmt.Fprintf(&b, "\t{Pattern: %s, Param: %s},\n", strconv.Quote(pattern), strconv.Quote(param))
	}
	if *kind == "static" {
		b.WriteString("\t{Pattern: \"/api/v1/users/by-id/{userId}\", Param: \"userId\"},\n")
	}
	b.WriteString("}\n\n")

	for i := 0; i < *count; i++ {
		fmt.Fprintf(&b, "//rr:route GET %s\nfunc (a *API) Route%04d() {}\n\n", routePattern(*kind, i), i)
	}
	if *kind == "static" {
		b.WriteString("//rr:route GET /api/v1/users/by-id/{userId}\nfunc (a *API) DynamicUser() {}\n")
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		panic(err)
	}
}

func routePattern(kind string, i int) string {
	switch kind {
	case "scale":
		return fmt.Sprintf("/gateway/v1/services/service-%04d/resources/{resourceId}", i)
	case "static":
		return fmt.Sprintf("/api/v1/users/reserved/action-%04d", i)
	default:
		panic("unknown fixture kind " + kind)
	}
}
