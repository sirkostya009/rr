// Command genmounts writes the 20 child APIs and composition source for the
// cross-package mount-chain benchmark.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	root := flag.String("root", ".", "mountchain package directory")
	count := flag.Int("count", 20, "number of child APIs")
	flag.Parse()

	var api strings.Builder
	api.WriteString("// Code generated by internal/genmounts. DO NOT EDIT.\n\npackage mountchain\n\nimport (\n")
	api.WriteString("\t\"github.com/sirkostya009/rr/bench/internal/stress\"\n")
	for i := 0; i < *count; i++ {
		fmt.Fprintf(&api, "\tservice%02d \"github.com/sirkostya009/rr/bench/adversarial/mountchain/service%02d\"\n", i, i)
	}
	api.WriteString(")\n\n//rr:api\ntype API struct {\n")
	for i := 0; i < *count; i++ {
		fmt.Fprintf(&api, "\tService%02d service%02d.API\n", i, i)
	}
	api.WriteString("}\n\nvar Routes = []stress.Route{\n")
	for i := 0; i < *count; i++ {
		fmt.Fprintf(&api, "\t{Pattern: \"/gateway/service-%02d/resources/{resourceId}\", Param: \"resourceId\"},\n", i)
	}
	api.WriteString("}\n")
	write(filepath.Join(*root, "api.go"), api.String())

	for i := 0; i < *count; i++ {
		dir := filepath.Join(*root, fmt.Sprintf("service%02d", i))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			panic(err)
		}
		src := fmt.Sprintf(`// Code generated by internal/genmounts. DO NOT EDIT.

package service%02d

//go:generate go run github.com/sirkostya009/rr/cmd $GOFILE

type API struct{}

//rr:route GET /gateway/service-%02d/resources/{resourceId}
func (a *API) Resource() {}
`, i, i)
		write(filepath.Join(dir, "routes.go"), src)
	}
}

func write(path, src string) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		panic(err)
	}
}
