// Command tsclient generates a TypeScript fetch client from rr routes, plus
// the TypeScript types that client sends and receives.
//
// It is a worked example of github.com/sirkostya009/rr/gen: load the packages,
// walk the routes, write the target language yourself. Nothing here is part of
// rr; copy it and change the output to taste.
//
//	go run . -o ../../web/src ../versioned/...
//
// Two generators over one set of packages. rr/gen knows every route and every
// binding; ggen/gen knows what is inside every JSON type those routes carry.
// Neither knows the other's half, which is why this program uses both.
package main

import (
	"fmt"
	"os"
	"path/filepath"
)

// header goes at the top of both generated files.
const header = "// Code generated by tsclient. DO NOT EDIT."

func main() {
	dir := "."
	clientFile, typesFile := "client.ts", "types.ts"
	var patterns []string
	args := os.Args[1:]
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "-o":
			i++
			if i == len(args) {
				fatalf("-o requires a directory")
			}
			dir = args[i]
		case "-client":
			i++
			if i == len(args) {
				fatalf("-client requires a file name")
			}
			clientFile = args[i]
		case "-types":
			i++
			if i == len(args) {
				fatalf("-types requires a file name")
			}
			typesFile = args[i]
		case "-h", "--help":
			fmt.Println("usage: tsclient [-o dir] [-client client.ts] [-types types.ts] <package patterns>")
			return
		default:
			patterns = append(patterns, args[i])
		}
	}
	if len(patterns) == 0 {
		fatalf("no package patterns")
	}
	issues, err := generate(dir, clientFile, typesFile, patterns)
	if err != nil {
		fatalf("%v", err)
	}
	for _, i := range issues {
		fmt.Fprintln(os.Stderr, "tsclient: not expressible in TypeScript:", i)
	}
}

// generate writes the client and its types into dir, and reports whatever the
// type emitter could not express.
func generate(dir, clientFile, typesFile string, patterns []string) ([]string, error) {
	// the types come first: what they are named decides what the client imports
	types, err := loadTypes(patterns)
	if err != nil {
		return nil, err
	}
	nm := newNames(types)

	routes, err := loadRoutes(patterns)
	if err != nil {
		return nil, err
	}
	client, err := renderClient(routes, nm, typesFile)
	if err != nil {
		return nil, err
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	issues, err := writeTypes(dir, typesFile, types, nm)
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(dir, clientFile), []byte(client), 0o644); err != nil { //nolint:gosec // generated source
		return nil, err
	}
	return issues, nil
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "tsclient: "+format+"\n", args...)
	os.Exit(1)
}
