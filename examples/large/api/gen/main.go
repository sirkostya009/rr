// Command gen writes routes.go: three literal sets of Count routes each, one
// per shape the hash planner has to handle.
package main

import (
	"fmt"
	"os"
	"strings"
)

// Count sits just above rr's hashSwitchMin.
const Count = 260

var syllables = [...]string{"ka", "lo", "mi", "ren", "tu", "vash", "o", "bel", "zi", "quor", "an", "dest"}

// Word is a deterministic pseudo-word, 2 to 12 bytes, unique per i.
func Word(i int) string {
	var b strings.Builder
	for n := i + len(syllables); n > 0; n /= len(syllables) {
		b.WriteString(syllables[n%len(syllables)])
	}
	return b.String()
}

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by gen. DO NOT EDIT.\n\npackage api\n\nconst Count = ")
	fmt.Fprintf(&b, "%d\n\n", Count)
	b.WriteString("var Words = [Count]string{\n")
	for i := range Count {
		fmt.Fprintf(&b, "\t%q,\n", Word(i))
	}
	b.WriteString("}\n")
	for i := range Count {
		// whole-path static set, equal lengths
		fmt.Fprintf(&b, "\n//rr:route GET /large/static/page-%03d\nfunc (a *Api) Static%03d() string { return \"static-%03d\" }\n", i, i, i)
		// descending literal before a param, equal lengths
		fmt.Fprintf(&b, "\n//rr:route GET /large/tenants/tenant-%03d/items/{id}\nfunc (a *Api) Tenant%03d(id string) string { return \"tenant-%03d:\" + id }\n", i, i, i)
		// keys sharing exactly one leading byte: too short a head to hoist, the
		// arms must keep comparing the whole key
		fmt.Fprintf(&b, "\n//rr:route GET /large/versions/v%03d/{id}\nfunc (a *Api) Version%03d(id string) string { return \"v%03d:\" + id }\n", i, i, i)
		// mixed lengths: the hash takes the length and bytes counted from the end
		fmt.Fprintf(&b, "\n//rr:route GET /large/words/%s/{id}\nfunc (a *Api) Word%03d(id string) string { return \"word-%03d:\" + id }\n", Word(i), i, i)
	}
	if err := os.WriteFile("routes.go", []byte(b.String()), 0o644); err != nil { //nolint:gosec // source file
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
